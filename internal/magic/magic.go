// Package magic serves the page MidoPress answers itself on its magic host
// (midopress.it): how to install the proxy certificate, the certificate files,
// a QR code, and a trust check. Nothing here is forwarded upstream.
package magic

import (
	"bytes"
	"crypto/sha256"
	"crypto/x509"
	"encoding/base64"
	"encoding/json"
	"encoding/pem"
	"errors"
	"fmt"
	"html/template"
	"net"
	"net/http"
	"net/url"
	"strconv"
	"strings"

	pkcs12 "software.sslmate.com/src/go-pkcs12"

	"github.com/goastian/midopress/internal/qr"
)

// P12Password is the password of the PKCS#12 trust store served at /ca.p12.
// The file holds only a public certificate; the password is a format
// requirement, not a secret.
const P12Password = "midopress"

const (
	maxQRLen    = 300
	certMaxAge  = "public, max-age=300"
	sourceURL   = "https://github.com/goastian/midopress"
	mimeX509CA  = "application/x-x509-ca-cert"
	mimePKCS12  = "application/x-pkcs12"
	mimeJSON    = "application/json; charset=utf-8"
	mimeHTML    = "text/html; charset=utf-8"
	mimeText    = "text/plain; charset=utf-8"
	mimeSVG     = "image/svg+xml"
	defaultHost = "midopress.it"
)

// Options configures the magic host handler.
type Options struct {
	// Host is the magic host name, "midopress.it" when empty.
	Host string
	// CertPEM is the CA certificate, never the key.
	CertPEM []byte
	// ProxyAddr is how clients reach the proxy, used only in the text.
	ProxyAddr string
	Version   string
	// Me describes the client making the request. It may be nil.
	Me func(r *http.Request) Me
}

// Me is what the proxy knows about the calling device.
type Me struct {
	Device        string `json:"device"`
	Addr          string `json:"addr"`
	Profile       string `json:"profile"`
	Requests      int64  `json:"requests"`
	BytesIn       int64  `json:"bytes_in"`
	BytesOut      int64  `json:"bytes_out"`
	Saved         int64  `json:"saved"`
	CATrustedHint string `json:"ca_trusted_hint"`
}

type handler struct {
	host      string
	pem       []byte
	der       []byte
	p12       []byte
	cert      *x509.Certificate
	opts      Options
	script    string
	css       string
	csp       string
	pageCSP   string
	qrSVG     template.HTML
	finger    string
	notBefore string
	notAfter  string
}

// New validates the certificate and returns the handler of the magic host.
func New(o Options) (http.Handler, error) {
	if o.Host == "" {
		o.Host = defaultHost
	}
	o.Host = normHost(o.Host)
	if strings.ContainsAny(o.Host, "\"'<>&\\ /") {
		return nil, fmt.Errorf("magic: invalid host %q", o.Host)
	}
	cert, err := parsePEM(o.CertPEM)
	if err != nil {
		return nil, err
	}
	if !cert.IsCA {
		return nil, errors.New("magic: certificate is not a CA")
	}
	p12, err := P12(o.CertPEM, P12Password)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(cert.Raw)
	h := &handler{
		host:      o.Host,
		pem:       pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: cert.Raw}),
		der:       cert.Raw,
		p12:       p12,
		cert:      cert,
		opts:      o,
		css:       pageCSS,
		script:    buildScript(o.Host),
		finger:    fingerprint(sum[:]),
		notBefore: cert.NotBefore.UTC().Format("2 Jan 2006"),
		notAfter:  cert.NotAfter.UTC().Format("2 Jan 2006"),
	}
	svg, err := qr.SVG("http://"+o.Host+"/ca.crt", qr.WithColors("currentColor", ""))
	if err != nil {
		return nil, err
	}
	h.qrSVG = template.HTML(strings.Replace(svg, ` xmlns="http://www.w3.org/2000/svg"`, "", 1)) //nolint:gosec // generated by internal/qr
	h.pageCSP = "default-src 'none'; style-src 'sha256-" + hash(h.css) +
		"'; script-src 'sha256-" + hash(h.script) +
		"'; img-src 'self'; connect-src https://" + o.Host +
		"; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"
	h.csp = "default-src 'none'; style-src 'sha256-" + hash(h.css) +
		"'; base-uri 'none'; frame-ancestors 'none'"
	return h, nil
}

func hash(s string) string {
	sum := sha256.Sum256([]byte(s))
	return base64.StdEncoding.EncodeToString(sum[:])
}

func fingerprint(sum []byte) string {
	parts := make([]string, len(sum))
	for i, b := range sum {
		parts[i] = fmt.Sprintf("%02X", b)
	}
	return strings.Join(parts, ":")
}

func parsePEM(certPEM []byte) (*x509.Certificate, error) {
	rest := certPEM
	for {
		var blk *pem.Block
		blk, rest = pem.Decode(rest)
		if blk == nil {
			return nil, errors.New("magic: no certificate in PEM data")
		}
		if blk.Type != "CERTIFICATE" {
			continue
		}
		c, err := x509.ParseCertificate(blk.Bytes)
		if err != nil {
			return nil, fmt.Errorf("magic: parse certificate: %w", err)
		}
		return c, nil
	}
}

// P12 returns a PKCS#12 trust store holding only the certificate in certPEM.
// It uses the legacy 3DES/SHA-1 parameters (the same ones as openssl
// -descert) because they are the ones every importer reads: Windows, macOS,
// Android, Java and OpenSSL 3. The AES-based modern encoders are rejected by
// older Windows and Android releases.
func P12(certPEM []byte, password string) ([]byte, error) {
	c, err := parsePEM(certPEM)
	if err != nil {
		return nil, err
	}
	out, err := pkcs12.LegacyDES.EncodeTrustStore([]*x509.Certificate{c}, password)
	if err != nil {
		return nil, fmt.Errorf("magic: encode PKCS#12: %w", err)
	}
	return out, nil
}

// IsMagic reports whether host (with or without port, any case, with or
// without a trailing dot) is the magic host.
func IsMagic(host, magicHost string) bool {
	m := normHost(magicHost)
	return m != "" && normHost(host) == m
}

func normHost(h string) string {
	h = strings.TrimSpace(h)
	if hp, _, err := net.SplitHostPort(h); err == nil {
		h = hp
	}
	h = strings.TrimSuffix(strings.TrimPrefix(strings.TrimSuffix(h, "]"), "["), ".")
	return strings.ToLower(h)
}

func (h *handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	hd := w.Header()
	hd.Set("X-Content-Type-Options", "nosniff")
	hd.Set("Cache-Control", "no-store")
	hd.Set("Referrer-Policy", "no-referrer")
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		hd.Set("Allow", "GET, HEAD")
		h.text(w, r, http.StatusMethodNotAllowed, "method not allowed\n")
		return
	}
	switch r.URL.Path {
	case "/":
		h.page(w, r)
	case "/ca.crt", "/ca.pem":
		h.file(w, r, h.pem, mimeX509CA, "midopress-ca.crt")
	case "/ca.der":
		h.file(w, r, h.der, mimeX509CA, "midopress-ca.der")
	case "/ca.p12":
		h.file(w, r, h.p12, mimePKCS12, "midopress-ca.p12")
	case "/qr.svg":
		h.qr(w, r)
	case "/check":
		hd.Set("Access-Control-Allow-Origin", "*")
		h.send(w, r, http.StatusOK, mimeJSON, []byte("{\"ok\":true}\n"))
	case "/api/v1/me":
		h.me(w, r)
	case "/health":
		h.text(w, r, http.StatusOK, "ok\n")
	default:
		h.notFound(w, r)
	}
}

func (h *handler) send(w http.ResponseWriter, r *http.Request, status int, ctype string, body []byte) {
	hd := w.Header()
	hd.Set("Content-Type", ctype)
	hd.Set("Content-Length", strconv.Itoa(len(body)))
	if hd.Get("Content-Security-Policy") == "" {
		hd.Set("Content-Security-Policy", "default-src 'none'; frame-ancestors 'none'")
	}
	w.WriteHeader(status)
	if r.Method != http.MethodHead {
		_, _ = w.Write(body)
	}
}

func (h *handler) text(w http.ResponseWriter, r *http.Request, status int, s string) {
	h.send(w, r, status, mimeText, []byte(s))
}

func (h *handler) file(w http.ResponseWriter, r *http.Request, body []byte, ctype, name string) {
	hd := w.Header()
	hd.Set("Cache-Control", certMaxAge)
	hd.Set("Content-Disposition", `attachment; filename="`+name+`"`)
	h.send(w, r, http.StatusOK, ctype, body)
}

func (h *handler) qr(w http.ResponseWriter, r *http.Request) {
	u := r.URL.Query().Get("u")
	if !h.allowedQRTarget(u) {
		h.text(w, r, http.StatusBadRequest, "only addresses on "+h.host+" are allowed\n")
		return
	}
	svg, err := qr.SVG(u)
	if err != nil {
		h.text(w, r, http.StatusBadRequest, "cannot encode this address\n")
		return
	}
	h.send(w, r, http.StatusOK, mimeSVG, []byte(svg))
}

func (h *handler) allowedQRTarget(s string) bool {
	if s == "" || len(s) > maxQRLen {
		return false
	}
	u, err := url.Parse(s)
	if err != nil || u.User != nil || u.Opaque != "" {
		return false
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return false
	}
	return IsMagic(u.Host, h.host)
}

func (h *handler) me(w http.ResponseWriter, r *http.Request) {
	if h.opts.Me == nil {
		h.notFound(w, r)
		return
	}
	b, err := json.Marshal(h.opts.Me(r))
	if err != nil {
		h.text(w, r, http.StatusInternalServerError, "error\n")
		return
	}
	h.send(w, r, http.StatusOK, mimeJSON, append(b, '\n'))
}

func (h *handler) notFound(w http.ResponseWriter, r *http.Request) {
	var buf bytes.Buffer
	if err := notFoundTmpl.Execute(&buf, struct {
		CSS  template.CSS
		Host string
	}{template.CSS(h.css), h.host}); err != nil { //nolint:gosec // static stylesheet
		h.text(w, r, http.StatusNotFound, "not found\n")
		return
	}
	w.Header().Set("Content-Security-Policy", h.csp)
	h.send(w, r, http.StatusNotFound, mimeHTML, buf.Bytes())
}
